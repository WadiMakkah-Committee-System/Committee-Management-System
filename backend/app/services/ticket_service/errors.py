"""
الهدف:
أخطاء طبقة خدمة التذاكر — كل خطأ له ترجمة HTTP واحدة بالراوت
(app/api/v1/tickets.py::_handle_errors)، ورسالة عربية جاهزة للعرض.
"""


class TicketNotFoundError(Exception):
    """
    التذكرة (أو الرسالة/المرفق) غير موجودة، أو موجودة لكن المستخدم ما له
    علاقة فيها — تُترجم 404 في الحالتين عمدًا، عشان ما ينكشف وجود تذكرة
    غيره (القسم 9 بالمواصفات).
    """


class TicketForbiddenError(Exception):
    """المستخدم ما يملك الصلاحية للعملية (مثال: بدون tickets.create) — تُترجم 403."""


class TicketInvalidStateError(Exception):
    """
    العملية لا تناسب حالة التذكرة الحالية (مغلقة، انتقال غير مسموح، استُلمت
    من عضو آخر، تعارض متزامن) — تُترجم 409.
    """


class TicketValidationError(ValueError):
    """مدخلات غير صالحة (طول النص، المرفقات، المسند إليه...) — تُترجم 400."""


class TicketStorageError(Exception):
    """تعذّر حفظ المرفق بالتخزين (مشكلة بالخادم وليست بالمدخلات) — تُترجم 503."""
