-- الهدف: تراجع جزئي عن 0035 — بعد التجربة الفعلية، لاما قررت (2026-09-16)
-- إن "البنود المستخرجة" تحديدًا تبقى حصرًا لرئيس اللجنة، ولا تظهر لعضو
-- اللجنة إطلاقًا — بعكس "عرض التفريغ الصوتي" و"عرض ملخص الاجتماع"
-- اللذين يبقيان متاحين للعضو تمامًا كما مُنحا بـ0035 (لم يُطلَب تغييرهما).
--
-- 0035 كانت منحت ai_items.view (المُعاد تسميتها هناك "عرض البنود
-- المستخرجة") افتراضيًا لدور "عضو اللجنة" ضمن دفعة الصلاحيات الثلاث —
-- هذا الملف يسحب ذلك المنح فقط، بلا أي لمس لبقية صلاحيات 0035 أو
-- لصلاحيات رئيس اللجنة (الذي يصل لكل شيء أصلًا عبر meetings.draft.view
-- الكاملة الممنوحة له يدويًا من قبل).
--
-- الصلاحية نفسها (ai_items.view) تبقى موجودة بالكتالوج وقابلة للمنح
-- يدويًا لاحقًا من شاشة "الأدوار والصلاحيات" لو غيّرت لاما رأيها مرة
-- أخرى — فقط المنح الافتراضي هو ما تغيّر هنا، والإنفاذ بالباك-إند
-- (meeting_service.list_extracted_items، OR بين meetings.draft.view
-- وai_items.view) يبقى كما هو بلا أي تعديل.
DELETE FROM role_permissions
WHERE permission_id = (SELECT permission_id FROM permissions WHERE code = 'ai_items.view')
  AND role_id = (SELECT role_id FROM roles WHERE committee_role_slug = 'member');
