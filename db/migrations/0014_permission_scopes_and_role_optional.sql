-- الهدف: إعادة تنظيم نظام الصلاحيات بناءً على مراجعة لاما 2026-08-30 —
-- فصل "الصلاحية" (ماذا يستطيع المستخدم أن يفعل) عن "نطاق الوصول" (على
-- أي بيانات) عن "قواعد العمل/الـWorkflow" (متى). هذا الملف يغطي طبقة
-- قاعدة البيانات فقط — الإنفاذ الفعلي لنطاق الوصول بالـBackend مرحلة
-- منفصلة لاحقة (لا تُكسَر أي وظيفة حالية بهذا الملف وحده: القيمة
-- الافتراضية 'all' لكل منح موجود = نفس السلوك الفعلي الحالي تمامًا،
-- إلا فيما هو موثّق صراحة أدناه كتغيير مقصود).
--
-- ============================ 1) عمود نطاق الوصول ============================
-- role_permissions كان جدول ربط ثنائي بدون أي بُعد إضافي (تملك الصلاحية
-- أو لا) — هذا بالضبط ما رفضته لاما: "لا تعتبر الصلاحية وحدها كافية
-- لتحديد الوصول إلى البيانات". النطاق الآن جزء من كل (دور، صلاحية) على
-- حدة، وليس افتراضًا ضمنيًا بالكود.
--
-- own: بيانات المستخدم نفسه، أو ما هو مالكه/عضو فيه/مسند إليه (التعريف
--      الدقيق لكل صلاحية يُحدَّد بطبقة الخدمة بالـBackend — مثال:
--      لـcommittees.view يعني "اللجان التي أنا رئيسها أو عضو فيها").
-- department: بيانات إدارة المستخدم نفسها فقط.
-- all: كل بيانات النظام ضمن هذه الصلاحية.
--
-- ملاحظة: القائمة الحالية (own/department/all) تغطي كل الحالات الموصوفة
-- بمراجعة 2026-08-30. لو احتاجت وحدة مستقبلية (مثال: الوثائق المشتركة
-- مع لجنة معيّنة) قيمة نطاق إضافية، تُضاف لاحقًا بـmigration جديد يُعدّل
-- الـCHECK أدناه (نفس نمط ALTER TYPE ... ADD VALUE المستخدم مسبقًا
-- لحالات committee_request_status بالملفين 0009/0010) — وليس بتعديل هذا
-- الملف بعد تطبيقه.
--
-- سبب اختيار عمود بسيط (VARCHAR + CHECK) بدل ENUM حقيقي: يسمح بإضافة
-- قيمة جديدة مستقبلًا بأمر ALTER بسيط دون قفل جدول كامل بطريقة ALTER TYPE
-- (الطريقة القديمة تتطلب COMMIT منفصل عن أول استخدام بنفس المعاملة).
ALTER TABLE role_permissions
    ADD COLUMN scope VARCHAR(20) NOT NULL DEFAULT 'all';

ALTER TABLE role_permissions
    ADD CONSTRAINT role_permissions_scope_chk
    CHECK (scope IN ('own', 'department', 'all'));

-- ============================ 2) الدور اختياري بمستوى المستخدم ============================
-- "عدم وجود دور لا يعني أن المستخدم لا يستطيع تسجيل الدخول" — مستخدم
-- بدون role_id يدخل النظام ويصل لبياناته الأساسية (GET /users/me) فقط،
-- بدون أي صلاحيات إضافية، لحين تعيين دور له. هذا لا يغيّر أي مستخدم
-- حالي (الكل عنده role_id فعليًا الآن) — يفتح فقط إمكانية تركه فارغًا
-- لاحقًا عند الإنشاء/التعديل.
ALTER TABLE users
    ALTER COLUMN role_id DROP NOT NULL;

-- ============================ 3) تنظيف كتالوج الصلاحيات ============================
-- (أ) users.login / users.logout: صلاحيتان بالكتالوج لكن غير مُستخدَمتين
-- بأي تحقق فعلي بالكود — تسجيل الدخول والخروج جزء من نظام المصادقة نفسه
-- (auth.py) وليسا صلاحية تُمنح أو تُسحب من دور. وجودهما بالكتالوج مضلل
-- (يوهم أنه يمكن منع دور من تسجيل الدخول عبر سحب الصلاحية، وهذا غير
-- صحيح فعليًا). الحذف يمسح تلقائيًا أي منح مرتبط بهما (ON DELETE CASCADE
-- على role_permissions.permission_id) — لا فقدان وظيفي فعلي لأنهما لم
-- يكونا يفرضان شيئًا أصلًا.
DELETE FROM permissions WHERE code IN ('users.login', 'users.logout');

-- (ب) committees.view_authorized: اسم غير دقيق (لاما 2026-08-30) — يوهم
-- أنه "اللجان المصرح بها" بمعنى عام، بينما المقصود الفعلي هو "اللجان
-- التي أنتمي إليها" (رئيسًا أو عضوًا). إعادة تسمية بـUPDATE (وليس
-- حذف+إدراج) عمدًا — يحافظ على permission_id نفسه فلا تنكسر صفوف
-- role_permissions المرتبطة به حاليًا.
UPDATE permissions
SET code = 'committees.view', label_ar = 'عرض اللجان التي أنتمي إليها'
WHERE code = 'committees.view_authorized';

-- (ج) tasks.view_all: نفس المشكلة اللي حذّرت منها لاما بالضبط ("لا تجعل
-- صلاحيات مثل عرض جميع المهام تمنح تلقائيًا الوصول لكل شي") — الاسم نفسه
-- يحقن "الكل" (all) داخل كود الصلاحية بدل ما يكون بُعد نطاق منفصل. لا
-- يوجد أي كود Backend يستخدم هذه الصلاحية بعد (وحدة المهام لم تُبنَ
-- بعد) — إعادة تسمية آمنة 100%، بلا أي أثر وظيفي.
UPDATE permissions
SET code = 'tasks.view', label_ar = 'عرض المهام'
WHERE code = 'tasks.view_all';

-- ============================ 4) تصحيح نطاق منح فعلي واحد ============================
-- دور "ادمن" هو المالك الوحيد حاليًا لصلاحية committees.view (بعد إعادة
-- التسمية أعلاه). القيمة الافتراضية 'all' كانت ستُبقي السلوك الحالي كما
-- هو (يرى كل اللجان المعتمدة بالنظام) — وهذا بالضبط الخطأ الذي طلبت لاما
-- تصحيحه: الاسم يوهم بأنه "لجانه"، فعليًا الكود لا يُصفّي بالعضوية إطلاقًا.
-- نطاقها الصحيح الفعلي own (اللجان التي هو رئيسها أو عضو فيها) —
-- الإنفاذ الفعلي لهذا الفلتر بطبقة الخدمة (committee_service.list_committees/
-- get_committee) مهمة مرحلة الـBackend القادمة، وليس هذا الملف.
UPDATE role_permissions
SET scope = 'own'
WHERE role_id = (SELECT role_id FROM roles WHERE name = 'ادمن')
  AND permission_id = (SELECT permission_id FROM permissions WHERE code = 'committees.view');

-- ============================ 5) منح جديد يدعم توحيد صلاحية تعديل طلب اللجنة ============================
-- مراجعة لاما رفضت استخدام committees.request.create كبديل غير مباشر
-- عن "أنا صاحب الطلب" لتبرير تعديل/إرسال المسودة الخاصة — سيُوحَّد كل
-- التعديل بمرحلة الـBackend القادمة تحت صلاحية واحدة committees.request.update
-- (بدل الخلط الحالي بين create/update حسب الدور). دور "ادمن" يحتاج هذا
-- المنح بنطاق own (تعديل مسودته/طلبه المُعاد فقط) ليحافظ على قدرته
-- الحالية بالضبط بعد ذلك التوحيد — بدون هذا المنح هنا الآن، أي طلب
-- تعديل من "ادمن" لمسودته سيُرفَض فور تفعيل التوحيد بالـBackend.
INSERT INTO role_permissions (role_id, permission_id, scope)
SELECT r.role_id, p.permission_id, 'own'
FROM roles r, permissions p
WHERE r.name = 'ادمن' AND p.code = 'committees.request.update'
ON CONFLICT (role_id, permission_id) DO UPDATE SET scope = 'own';
