-- الهدف: الحضور التلقائي لاجتماعات Teams المدمجة (قرار لاما 2026-11-03 —
-- دفعة تحسينات الاجتماع، البند 2).
--
-- السياق: جدول meeting_attendance موجود منذ 0022 (أيام Agora) وفاضي بالإنتاج
-- (0 صف — فُحص قبل كتابة هذا الملف). عمود agora_uid إلزامي فيه وما عاد له معنى
-- بعد إزالة Agora (2026-11-02).
--
-- قواعد العمل المعتمدة (لاما 2026-11-03):
-- 1) جلسة حضور = من لحظة دخول العضو للاجتماع فعليًا (بعد القبول من قاعة
--    الانتظار، لا مجرد فتح الصفحة) إلى خروجه. دخل وطلع أكثر من مرة ⇒ أكثر من جلسة.
-- 2) جدول الحضور بصفحة الاجتماع والمحضر: الاسم، أول دخول، آخر خروج، إجمالي المدة.
-- 3) نبضة كل دقيقة تقريبًا (last_seen_at) — لو انقطع المتصفح فجأة بدون تسجيل
--    خروج، تُعتبر الجلسة منتهية عند آخر نبضة بدل ما تبقى "مفتوحة للأبد".
--
-- التغييرات:
-- أ) حذف agora_uid (لا بيانات قائمة).
-- ب) last_seen_at (آخر نبضة، إلزامي، افتراضي now()).
--
-- أثر على البيانات القائمة: لا شيء (الجدول فاضي).
-- =====================================================================

BEGIN;

ALTER TABLE meeting_attendance DROP COLUMN IF EXISTS agora_uid;

ALTER TABLE meeting_attendance
    ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now();

COMMENT ON COLUMN meeting_attendance.last_seen_at IS
    'آخر نبضة من جهاز العضو أثناء الاجتماع — تُستخدم كوقت خروج لو انقطع بدون تسجيل خروج';

COMMIT;
