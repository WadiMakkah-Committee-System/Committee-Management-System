-- المخزّنة في enum بايثون AuditAction تُبنى من .name وليس .value، فأي
-- فرق بينهما يُنتج خطأ وقت التشغيل. 'returned' متّسقة أيضًا مع اسم حالة
-- الطلب committee_request_status.returned.
