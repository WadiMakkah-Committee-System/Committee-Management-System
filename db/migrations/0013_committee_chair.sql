-- الهدف: فصل واضح بين "الدور العام" (System Role — صلاحيات المستخدم
-- الدائمة بالنظام) و"رئاسة اللجنة" (Committee Chair — دور مؤقت مرتبط
-- بعضوية المستخدم داخل لجنة محددة فقط)، حسب قرار موثّق من صاحبة المشروع
-- 2026-08-27: حُذف دورا "رئيس لجنة"/"عضو لجنة" من كتالوج الأدوار العامة
-- نهائيًا، ولا يُعاد إضافتهما هناك؛ رئيس اللجنة يُحدَّد بدلًا من ذلك عند
-- تقديم طلب تشكيل اللجنة (عضو واحد من ضمن الأعضاء المقترحين)، ويُنسخ
-- تلقائيًا للجنة المعتمدة عند الموافقة.
--
-- التصميم: عمود chair_user_id بسيط على كل من committee_formation_requests
-- وcommittees (بدل تحويل committee_members/committee_formation_request_
-- members من جدول وسيط بسيط إلى Association Object لإضافة عمود is_chair
-- لكل صف) — أقل تغييرًا وأبسط استعلامًا، ويكفي تمامًا لأن "من هو الرئيس"
-- سؤال عن اللجنة/الطلب نفسه (قيمة واحدة)، وليس صفة لكل عضو.
--
-- القيد "رئيس واحد فقط لكل لجنة" مضمون بنيويًا: عمود واحد (لا قائمة)،
-- والتحقق من أن الرئيس هو فعلًا أحد الأعضاء المقترحين/المعتمدين يُفرض في
-- طبقة الخدمة (committee_service.py)، بنفس نمط التحقق من صحة الأعضاء
-- أنفسهم (_resolve_members) — وليس بقيد قاعدة بيانات مباشر، لأن Postgres
-- لا يدعم FK مركّب سهل ضد جدول وسيط بهذا الشكل.
-- =====================================================================

ALTER TABLE committee_formation_requests
    ADD COLUMN chair_user_id UUID REFERENCES users(user_id);

ALTER TABLE committees
    ADD COLUMN chair_user_id UUID REFERENCES users(user_id);
